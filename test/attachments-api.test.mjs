import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createFixture, configure, session } from './auth-helpers.mjs';

test('real Pi attachment tool persists files and checks group membership on every read', { timeout: 120_000 }, async () => {
  const fixture=await createFixture({prefix:'attachments-api',options:{scheduler:{autoStart:false},channels:{autoStart:false}}});
  const admin=fixture.client(),member=fixture.client(),outsider=fixture.client();
  const password='attachment-fixture-password';
  try{
    assert.equal((await admin.request('/auth/setup',{method:'POST',body:{username:'attach-admin',displayName:'Attachment Admin',password}})).response.status,201);
    const memberAccount=(await admin.request('/admin/users',{method:'POST',body:{username:'attach-member',displayName:'Member',password,role:'member'}})).data.user;
    await admin.request('/admin/users',{method:'POST',body:{username:'attach-outsider',displayName:'Outsider',password,role:'member'}});
    await member.request('/auth/login',{method:'POST',body:{username:'attach-member',password}});
    await outsider.request('/auth/login',{method:'POST',body:{username:'attach-outsider',password}});
    await configure(admin,fixture);
    const chat=await session(admin,'File delivery');
    await admin.request(`/sessions/${chat.id}/members`,{method:'POST',body:{userIds:[memberAccount.id]}});
    await admin.request(`/sessions/${chat.id}`,{method:'PATCH',body:{mode:'workspace'}});
    const contents=Buffer.from('name,value\n实际结果,42\n');
    await fs.writeFile(path.join(chat.cwd,'结果.csv'),contents);
    await member.send(chat.id,'[attach-file:结果.csv] [omit-attachment-link]');
    assert.ok(fixture.mock.requests.at(-1).tools.some(tool=>tool.function.name==='attach_file'));
    const history=(await member.request(`/sessions/${chat.id}`)).data.messages;
    const final=history.filter(message=>message.role==='assistant'&&!message.tools?.length).at(-1);
    assert.match(final.content,/文件已经生成/);
    const attachmentPath=final.content.match(/(\/api\/sessions\/[^\s)]+\/attachments\/[a-f0-9-]+(?:\?[^\s)]*)?)/)?.[1];
    assert.ok(attachmentPath,final.content);
    const route=attachmentPath.slice('/api'.length);
    const fetched=await member.fetch(route);
    assert.equal(fetched.status,200);
    assert.deepEqual(Buffer.from(await fetched.arrayBuffer()),contents);
    assert.match(fetched.headers.get('content-disposition'),/^attachment;/);
    assert.equal(fetched.headers.get('content-type'),'application/octet-stream');
    assert.equal(fetched.headers.get('cache-control'),'private, no-store');
    assert.equal((await fixture.client().fetch(route)).status,401);
    assert.equal((await outsider.fetch(route)).status,404);
    const other=await session(admin,'Other group');
    assert.equal((await admin.fetch(route.replace(chat.id,other.id))).status,404);
    await fs.writeFile(path.join(chat.cwd,'结果.csv'),'changed after sending');
    await fixture.stop();await fixture.start();
    const reopened=await member.fetch(route);
    assert.equal(reopened.status,200);
    assert.deepEqual(Buffer.from(await reopened.arrayBuffer()),contents);
    assert.ok((await member.request(`/sessions/${chat.id}`)).data.messages.some(message=>message.content?.includes(attachmentPath)));
    const head=await member.fetch(route,{method:'HEAD'});
    assert.equal(head.status,200);assert.equal(await head.text(),'');assert.equal(Number(head.headers.get('content-length')),contents.length);
    const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aXioAAAAASUVORK5CYII=','base64');
    await fs.writeFile(path.join(chat.cwd,'截图.png'),png);
    await admin.send(chat.id,'[attach-file:截图.png] [omit-attachment-link]');
    const imageMessage=(await member.request(`/sessions/${chat.id}`)).data.messages.filter(message=>message.role==='assistant'&&!message.tools?.length).at(-1);
    assert.match(imageMessage.content,/!\[截图\.png\]/);
    const imageRoute=imageMessage.content.match(/(\/api\/sessions\/[^\s)]+\/attachments\/[a-f0-9-]+(?:\?[^\s)]*)?)/)[1].slice('/api'.length);
    const imageResponse=await member.fetch(imageRoute);
    assert.equal(imageResponse.headers.get('content-type'),'image/png');
    assert.match(imageResponse.headers.get('content-disposition'),/^inline;/);
    assert.deepEqual(Buffer.from(await imageResponse.arrayBuffer()),png);
    assert.match((await member.fetch(imageRoute+'&download=1')).headers.get('content-disposition'),/^attachment;/);
    assert.equal((await admin.request(`/sessions/${chat.id}/members/${memberAccount.id}`,{method:'DELETE',body:{}})).response.status,200);
    assert.equal((await member.fetch(route)).status,404);
    await admin.request(`/sessions/${chat.id}`,{method:'PATCH',body:{mode:'read-only'}});
    await admin.send(chat.id,'Check available tools.');
    assert.ok(!fixture.mock.requests.at(-1).tools.some(tool=>tool.function.name==='attach_file'));
  }finally{await fixture.close();}
});
